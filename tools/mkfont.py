"""Convert a PSF1/PSF2 console font (e.g. Terminus from console-setup) into a C header with
ASCII 32..126 glyphs.  Usage: mkfont.py font.psf[.gz] NAME out.h

Terminus Font (c) Dimitar Toshkov Zhekov, SIL Open Font License 1.1.
"""
import sys, gzip, struct


def load(path):
    raw = open(path, 'rb').read()
    if raw[:2] == b'\x1f\x8b':
        raw = gzip.decompress(raw)
    if raw[:2] == b'\x36\x04':                      # PSF1
        mode, h = raw[2], raw[3]
        n = 512 if mode & 1 else 256
        w, hdr, bpg = 8, 4, h
        glyphs = [raw[hdr + i * bpg: hdr + (i + 1) * bpg] for i in range(n)]
        table = raw[hdr + n * bpg:] if mode & 2 else None
        uni = {}
        if table:
            i, g = 0, 0
            while i + 1 < len(table) and g < n:
                v = struct.unpack('<H', table[i:i + 2])[0]; i += 2
                if v == 0xFFFF: g += 1
                elif v != 0xFFFE: uni.setdefault(v, g)
        return w, h, glyphs, uni
    magic, ver, hdr, flags, n, bpg, h, w = struct.unpack('<8I', raw[:32])
    assert magic == 0x864ab572, 'not a PSF font'
    glyphs = [raw[hdr + i * bpg: hdr + (i + 1) * bpg] for i in range(n)]
    uni = {}
    if flags & 1:
        t = raw[hdr + n * bpg:]
        for g, entry in enumerate(t.split(b'\xff')[:n]):
            for ch in entry.split(b'\xfe')[0].decode('utf-8', 'replace'):
                uni.setdefault(ord(ch), g)
    return w, h, glyphs, uni


def main():
    path, name, out = sys.argv[1:4]
    w, h, glyphs, uni = load(path)
    rowbytes = (w + 7) // 8
    lines = ['/* generated by tools/mkfont.py from %s - Terminus Font, SIL OFL 1.1 */' % path.split('/')[-1],
             '#define %s_W %d' % (name.upper(), w), '#define %s_H %d' % (name.upper(), h),
             '#define %s_ROWBYTES %d' % (name.upper(), rowbytes),
             'static const unsigned char %s_data[95][%d] = {' % (name, rowbytes * h)]
    for c in range(32, 127):
        g = glyphs[uni.get(c, c)]
        lines.append('  {' + ','.join('0x%02x' % b for b in g[:rowbytes * h]) + '}, /* %r */' % chr(c))
    lines.append('};')
    open(out, 'w', newline='\n').write('\n'.join(lines) + '\n')
    print('%s: %dx%d, %d glyphs in font' % (out, w, h, len(glyphs)))


if __name__ == '__main__':
    main()
