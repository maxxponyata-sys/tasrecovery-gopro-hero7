W, H = 320, 480
BG = (12, 14, 18)
FG = (232, 234, 239)
DIM = (130, 138, 150)
ACC = (26, 161, 232)
RED = (229, 72, 77)
GRN = (60, 200, 110)


class Canvas:
    def __init__(self):
        self.px = bytearray(bytes(BG) * (W * H))

    def rect(self, x, y, w, h, c):
        for yy in range(max(0, y), min(H, y + h)):
            row = yy * W
            for xx in range(max(0, x), min(W, x + w)):
                i = (row + xx) * 3
                self.px[i:i + 3] = bytes(c)

    def text(self, x, y, s, c=FG, scale=2):
        for ch in s.upper():
            g = FONT.get(ch, FONT[' '])
            for ry, row in enumerate(g):
                for rx, bit in enumerate(row):
                    if bit == '1':
                        self.rect(x + rx * scale, y + ry * scale, scale, scale, c)
            x += 6 * scale
        return x

    def center(self, y, s, c=FG, scale=2):
        self.text((W - len(s) * 6 * scale) // 2, y, s, c, scale)

    def save(self, path):
        with open(path, 'wb') as f:
            f.write(b'P6\n%d %d\n255\n' % (W, H))
            f.write(self.px)


MENU = ["REBOOT SYSTEM", "REBOOT BOOTLOADER", "SD CARD AS USB DRIVE", "BACKUP TO SD CARD", "POWER OFF"]


def header(c, sub="ADB READY - USB"):
    c.rect(0, 0, W, 44, (24, 27, 34))
    c.center(8, "TASRECOVERY", ACC, 3)
    c.center(52, "GOPRO HERO7 - APQ8053", DIM, 2)
    c.center(72, sub, GRN, 2)


def main(out):
    os.makedirs(out, exist_ok=True)
    for sel in range(len(MENU)):
        c = Canvas()
        header(c)
        y = 104
        for i, item in enumerate(MENU):
            if i == sel:
                c.rect(8, y - 6, W - 16, 30, ACC)
                c.text(18, y, "> " + item, (255, 255, 255), 2)
            else:
                c.text(18, y, "  " + item, FG, 2)
            y += 36
        c.center(290, "SHORT PRESS: NEXT", DIM, 2)
        c.center(306, "HOLD 1 SEC: SELECT", DIM, 2)
        c.save(os.path.join(out, 'menu%d.ppm' % sel))

    def status(name, lines, color):
        c = Canvas()
        header(c)
        y = 130
        for ln in lines:
            c.center(y, ln, color, 2)
            y += 26
        c.save(os.path.join(out, name + '.ppm'))

    status('busy', ["WORKING...", "", "DO NOT POWER OFF"], FG)
    status('done', ["DONE", "", "PRESS ANY BUTTON"], GRN)
    status('fail', ["FAILED", "", "SEE /TMP/TASREC.LOG", "PRESS ANY BUTTON"], RED)
    status('ums', ["SD CARD IS NOW", "A USB DRIVE ON THE PC", "", "EJECT IT ON THE PC,", "THEN HOLD 1 SEC", "TO RETURN"], ACC)
    status('nosd', ["NO SD CARD FOUND", "", "PRESS ANY BUTTON"], RED)
    status('bye', ["REBOOTING..."], FG)
    status('off', ["POWERING OFF..."], FG)
    print('screens written to', out)


